#!/usr/bin/env python3
"""Find the dynamic stack allocations of the asm 3D engine and write
recomp/fixups_patches.txt.

The engine (0x46c000..0x4a7000, machine-translated code that keeps its
"registers" in memory at 0x4e949c..) allocates its frame with
    mov [r], -N ; add esp, [r]   ...   pop [r] ; sub esp, [r]
Ghidra cannot follow ESP through a memory operand, so the decompiled
function loses track of its stack.  `add esp, [r]` and `add esp, imm32` are
both 6 bytes, so the analysis copy is rewritten to the constant form.
"""
import os, re, sys, struct
import pefile, capstone

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
sys.path.insert(0, os.path.join(ROOT, 'recomp'))
from export_parse import load_export

fs = load_export(os.path.join(ROOT, 'recomp', 'export', 'functions.txt'))
pe = pefile.PE(os.path.join(ROOT, 'game', 'DAYTONA USA Deluxe.exe'))
md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
out = []
for f in fs:
    if f.thunk or f.addr >= 0x4a7e30:
        continue
    code = pe.get_data(f.addr - 0x400000, f.end - f.addr + 16)
    prev = None
    imm = None
    subs = []
    for i in md.disasm(code, f.addr):
        if i.address > f.end:
            break
        if i.mnemonic in ('add', 'sub') and i.op_str.startswith('esp, dword ptr ['):
            mem = re.search(r'\[(0x[0-9a-f]+)\]', i.op_str).group(1)
            if i.mnemonic == 'add' and prev is not None and prev.mnemonic == 'mov' and \
                    prev.op_str.startswith('dword ptr [%s], ' % mem):
                imm = int(prev.op_str.split(', ')[1], 16) & 0xffffffff
                out.append('patch %08x 81c4%s  # add esp, [%s] -> add esp, 0x%x' % (
                    i.address, struct.pack('<I', imm).hex(), mem, imm))
            elif i.mnemonic == 'sub':
                subs.append((i.address, mem))
        prev = i
    if imm is not None:
        for a, mem in subs:
            out.append('patch %08x 81ec%s  # sub esp, [%s] -> sub esp, 0x%x' % (a, struct.pack('<I', imm).hex(), mem, imm))
# shared epilogues reached by jumps (e.g. 0x48aba7 jumps into 0x48abde) are
# covered because they belong to the function that also allocates the frame
open(os.path.join(ROOT, 'recomp', 'fixups_patches.txt'), 'w').write(
    '# generated by tools/find_esp_patches.py\n' + '\n'.join(out) + '\n')
print(len(out), 'patches')
