#!/usr/bin/env python3
"""Generate runtime/w32_stubs.c: a logging stub for every import in
recomp/gen/w32_protos.h that runtime/*.c does not implement yet."""
import os, re, glob

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
protos = open(os.path.join(ROOT, 'recomp', 'gen', 'w32_protos.h')).read()
defined = set()
for f in glob.glob(os.path.join(ROOT, 'runtime', '*.c')):
    if f.endswith('w32_stubs.c'):
        continue
    for m in re.finditer(r'^[A-Za-z_][\w \*]*?\b(w32_\w+)\s*\([^;]*?\)\s*\{', open(f, errors='replace').read(), re.M | re.S):
        defined.add(m.group(1))
out = ['/* generated by tools/gen_stubs.py - imports with no implementation yet */',
       '#include "w32.h"', '']
n = 0
for line in protos.split('\n'):
    m = re.match(r'^(.*?)\b(w32_\w+)\s*\((.*)\);', line)
    if not m or m.group(2) in defined:
        continue
    ret, name, args = m.group(1).strip(), m.group(2), m.group(3)
    body = '    TRACE_STUB("%s");\n' % name[4:]
    if ret != 'void':
        body += '    return 0;\n'
    out.append('%s %s(%s)\n{\n%s}\n' % (ret, name, args, body))
    n += 1
open(os.path.join(ROOT, 'runtime', 'w32_stubs.c'), 'w', newline='\n').write('\n'.join(out))
print('%d stubs, %d implemented' % (n, len(defined)))
